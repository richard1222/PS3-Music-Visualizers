#ifndef NL_YOUTUBE_H
#define NL_YOUTUBE_H

#define MAX_STREAM_URL     2048
#define MAX_STREAM_FORMATS 24
#define MAX_AUDIO_TRACKS   32

/* one selectable stream. url may be empty if the source needs deobfuscation
 * we haven't done yet (e.g. youtube's cipher) -- formatCount still reflects
 * what the source offered. */
typedef struct {
   int  itag;              /* source-specific format id (0 if n/a) */
   int  width, height;
   int  fps;               /* frames per second (0 if the source doesn't say) */
   int  hasVideo, hasAudio;
   int  needsCipher;       /* 1 = url is signature-ciphered, not yet playable */
   char container[8];      /* "mp4" */
   char url[MAX_STREAM_URL];
   int  isLiveSegmented;   /* url is a DASH segment base */
   long liveStartSq;       /* earliest segment number available (DVR window start) */
   long liveEdgeSq;        /* most recent segment number available (live edge) */
   int  isDrc;             /* audio: dynamic-range-compressed copy */
   int  isVp9;             /* video: VP9 profile 0 in WebM */
   int  isOpus;            /* audio: Opus in WebM (itag 251) */
   int  vp9Fallback;       /* VP9 1080p kept beside 1440p, never offered */
} StreamFormat;

/* How much an audio track is worth playing by default, lowest first. */
enum { AUDIO_RANK_DESCRIPTIVE, AUDIO_RANK_DUBBED, AUDIO_RANK_OTHER, AUDIO_RANK_DEFAULT, AUDIO_RANK_ORIGINAL };

/* one audio track (language) of a video that has several. */
typedef struct {
   char id[24];
   char name[64];
   int  rank;              /* AUDIO_RANK_* */
   int  itag;
   int  isDrc;
   char url[MAX_STREAM_URL];
   int  opusItag;
   int  opusIsDrc;
   char opusUrl[MAX_STREAM_URL];
} AudioTrack;

#define MAX_CAPTION_TRACKS 8

typedef struct {
   char languageCode[12];
   char name[48];
   char url[MAX_STREAM_URL];
   int  translatable;
   int  autoGenerated;
   int  translated;
} CaptionTrack;

typedef struct {
   char title[256];
   char description[2048];
   int  captionCount;
   CaptionTrack captions[MAX_CAPTION_TRACKS];
   char translateCode[12];
   char translateName[48];
   int  durationSeconds;
   int  isLive;
   int  isPostLive;
   int  liveDvr;
   int  liveSegmentSec;
   int  liveWindowSec;
   int  formatCount;
   StreamFormat formats[MAX_STREAM_FORMATS];
   int  audioTrackCount;
   AudioTrack audioTracks[MAX_AUDIO_TRACKS];
} StreamInfo;

#define MAX_SEARCH_RESULTS 500

typedef struct {
   char videoId[16];
   char channelId[32];
   char title[160];
   char duration[12];      /* "3:15" (empty if unknown / live) */
   char author[48];
   char views[24];         /* "6,100 views" */
   char published[24];     /* "1 hour ago" */
   int  isLive;
   int  downloadState;
} SearchResult;

/* "3:15" / "1:02:33" -> seconds. 0 for anything that is not a plain duration. */
static inline int durationToSeconds(const char *text)
{
   int parts[3] = {0, 0, 0}, count = 0, value = 0, digits = 0;
   for (const char *p = text; ; p++) {
      if (*p >= '0' && *p <= '9') {
         if (value > 100000) return 0;
         value = value * 10 + (*p - '0'); digits++; continue;
      }
      if (*p != ':' && *p != 0) return 0;
      if (!digits || count == 3) return 0;
      parts[count++] = value;
      if (*p == 0) break;
      value = 0; digits = 0;
   }
   if (count == 1) return parts[0];
   if (count == 2) return parts[0] * 60 + parts[1];
   return parts[0] * 3600 + parts[1] * 60 + parts[2];
}

#define MAX_CONTINUATION 4096
#define MAX_SORT_TOKEN   512

typedef struct {
   int          count;
   char         continuation[MAX_CONTINUATION];
   char         channelName[48];
   char         sortTokens[3][MAX_SORT_TOKEN];
   SearchResult items[MAX_SEARCH_RESULTS];
} SearchResults;

/* trending categories; order matches TRENDING_FEEDS in youtube.c */
typedef enum {
   TREND_GAMING,
   TREND_SPORTS,
   TREND_PODCASTS,
   TREND_COUNT
} TrendingCategory;

typedef enum {
   SORT_RELEVANCE,
   SORT_VIEWS,
   SORT_COUNT
} SortOrder;

/* ---- Neon Lounge API ------------------------------------------------------
 * All network functions BLOCK; call them from the yt worker thread only
 * (yt_worker.h), never from the UI thread. */

/* Directory the visitor session persists in (the app USRDIR, no trailing
 * slash needed). Call once at startup. */
void yt_set_data_dir(const char *dir);
const char *yt_data_dir(void);

/* Text search, first page. 0 ok, negative on error. */
int yt_search(const char *query, SearchResults *out);

/* A trending category feed (TREND_*), first page. 0 ok, negative on error. */
int yt_trending(int category, SearchResults *out);

/* Resolve a video id or YouTube URL to its format ladder. 0 ok. */
int yt_extract(const char *input, StreamInfo *out);

/* Forget the saved anonymous visitor session (Settings escape hatch). */
void yt_reset_visitor(void);

/* 1 when a visitor session is saved on disk. */
int yt_visitor_persisted(void);

/* Log sink for the extractor's diagnostics. The default writes to
 * <data dir>/youtube.log on PS3 and to stderr elsewhere; the count is
 * capped per process so a long session cannot grow the file forever. */
void yt_log_sink(const char *level, const char *line);

/* ---- host-test exports ---------------------------------------------------- */
int yt_parse_results(const char *resp, int respLen, SearchResults *out);
int yt_parse_player(const char *resp, int respLen, StreamInfo *out);
int yt_visitor_store(const char *data);
int yt_visitor_load(char *out, int cap);

#endif
